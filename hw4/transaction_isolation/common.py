import os

from sqlalchemy import Engine, create_engine, text

DATABASE_URL = os.getenv(
    "DATABASE_URL",
    "postgresql+psycopg://shop:shop@localhost:7432/shop",
)


def engine_for(isolation_level: str) -> Engine:
    return create_engine(
        DATABASE_URL,
        isolation_level=isolation_level,
        pool_pre_ping=True,
    )


def prepare_value_table(value: int = 100) -> None:
    engine = engine_for("READ COMMITTED")
    with engine.begin() as connection:
        connection.execute(
            text(
                """
                CREATE TABLE IF NOT EXISTS isolation_values (
                    id INTEGER PRIMARY KEY,
                    value INTEGER NOT NULL
                )
                """
            )
        )
        connection.execute(text("DELETE FROM isolation_values"))
        connection.execute(
            text("INSERT INTO isolation_values (id, value) VALUES (1, :value)"),
            {"value": value},
        )
    engine.dispose()


def prepare_phantom_table() -> None:
    engine = engine_for("READ COMMITTED")
    with engine.begin() as connection:
        connection.execute(
            text(
                """
                CREATE TABLE IF NOT EXISTS isolation_orders (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    amount INTEGER NOT NULL
                )
                """
            )
        )
        connection.execute(text("TRUNCATE isolation_orders RESTART IDENTITY"))
        connection.execute(
            text("INSERT INTO isolation_orders (amount) VALUES (100), (200)")
        )
    engine.dispose()


def prepare_doctors_table() -> None:
    engine = engine_for("READ COMMITTED")
    with engine.begin() as connection:
        connection.execute(
            text(
                """
                CREATE TABLE IF NOT EXISTS isolation_doctors (
                    id INTEGER PRIMARY KEY,
                    on_call BOOLEAN NOT NULL
                )
                """
            )
        )
        connection.execute(text("DELETE FROM isolation_doctors"))
        connection.execute(
            text(
                """
                INSERT INTO isolation_doctors (id, on_call)
                VALUES (1, TRUE), (2, TRUE)
                """
            )
        )
    engine.dispose()
